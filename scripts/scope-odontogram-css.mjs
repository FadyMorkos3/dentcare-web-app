import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const entry = "node_modules/react-advanced-odontogram/dist/style.css"
const target = join(root, "src/styles/odontogram.scoped.css")
const SCOPE = ".odon-scope"
// Rules that would restyle the host app rather than the chart.
const DROP = new Set(["*", ":root *", "html", "body", "html,body", "html body"])
// `.dark` is set on an ancestor by the library's own dark mode; keep it working
// inside the scope by folding it onto the scope element itself.
const DARK = /^\.dark(?![\w-])/

function matchingBrace(text, open) {
  let depth = 0
  let quote = ""
  for (let i = open; i < text.length; i++) {
    const ch = text[i]
    if (quote) {
      if (ch === quote && text[i - 1] !== "\\") quote = ""
      continue
    }
    if (ch === '"' || ch === "'") {
      quote = ch
      continue
    }
    if (ch === "{") depth++
    else if (ch === "}") {
      depth--
      if (depth === 0) return i
    }
  }
  throw new Error("Unbalanced braces in stylesheet")
}

function splitSelectors(prelude) {
  const parts = []
  let depth = 0
  let cur = ""
  for (const ch of prelude) {
    if (ch === "(" || ch === "[") depth++
    else if (ch === ")" || ch === "]") depth--
    if (ch === "," && depth === 0) {
      parts.push(cur)
      cur = ""
    } else cur += ch
  }
  parts.push(cur)
  return parts.map((p) => p.replace(/\s+/g, " ").trim()).filter(Boolean)
}

function scopeSelector(sel) {
  if (sel.startsWith(SCOPE)) return sel
  if (DARK.test(sel)) return `${SCOPE}.dark${sel.replace(DARK, "")}`
  if (sel.startsWith(":root")) return `${SCOPE}${sel.slice(5)}`
  if (/^(::|[&+~>])/.test(sel)) return sel
  if (/^html[\s.[]/.test(sel)) return `${SCOPE}${sel.slice(4)}`
  return `${SCOPE} ${sel}`
}

function rewrite(text) {
  let out = ""
  let prelude = ""
  let i = 0
  while (i < text.length) {
    const ch = text[i]
    if (ch === "}" || ch === "{" || ch === ";") {
      const head = prelude.trim()
      prelude = ""
      if (ch === "{") {
        const end = matchingBrace(text, i)
        const body = text.slice(i + 1, end)
        if (
          /^@(keyframes|-[\w-]+-keyframes)/.test(head) ||
          /^@(font-face|charset)/.test(head)
        ) {
          out += `${head}{${body}}`
        } else if (/^@(media|supports|layer|container)/.test(head)) {
          out += `${head}{${rewrite(body)}}`
        } else {
          const kept = splitSelectors(head)
            .filter((sel) => !DROP.has(sel))
            .map(scopeSelector)
          if (kept.length) out += `${kept.join(",")}{${body}}`
        }
        i = end + 1
        continue
      }
      if (ch === ";" && head && !head.startsWith("@")) out += `${head};`
      i++
      continue
    }
    prelude += ch
    i++
  }
  return out
}

const css = readFileSync(join(root, entry), "utf8").replace(
  /\/\*[\s\S]*?\*\//g,
  "",
)
const scoped = rewrite(css)
const body = `/* GENERATED by scripts/scope-odontogram-css.mjs — do not edit by hand.
 * Scoped copy of the react-advanced-odontogram stylesheet.
 * The package ships global rules (:root tokens, body, select) and generic class
 * names (.card, .btn, .topbar, .brand, .dot) that collide with this app's own
 * stylesheet, so every selector is re-rooted under ${SCOPE}.
 * Wrap <OdontogramShell /> in an element carrying that class (plus "dark" when
 * dark mode is on) and add this file to src/main.tsx. Run
 * "npm run scope:odontogram" after bumping the package. */
${scoped}
`
mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, body)
console.log(
  `Wrote ${target} (${(body.length / 1024).toFixed(1)} kB, ${scoped.split("}").length} rules)`,
)
